#pragma once

// 交互模式只控制本地事件分发，不能作为 ShapeType 写入绘画协议。
enum class CanvasInteractionMode
{
    Draw, // 由绘图 Tool 创建和更新笔迹。
    Select, // 使用 Qt 默认选择规则操作图片图元。
    Pan // 只滚动本地视口，不修改场景图元。
};
